export function getTopicsForSubject(subjectId: string, examId?: string): Topic[] {
  if (examId) {
    try {
      const { getExamBlueprint } = require("./examBlueprints");
      const { getSubtopicsForTopic } = require("./subtopicRegistry");
      const bp = getExamBlueprint(examId);

      const subjectBp = bp?.subjects?.find((s: { id: string }) => s.id === subjectId);
      if (subjectBp && subjectBp.topics && subjectBp.topics.length > 0) {
        return subjectBp.topics.map((t: {
          id: string;
          name: string;
          description?: string;
          difficulty?: string;
          questionTypes?: string[];
          weightage?: string;
        }) => ({
          id: t.id,
          subjectId: subjectId,
          examId: examId,
          name: t.name,
          difficulty: (t.difficulty as any) || "Exam Level",
          progress: 0,
          lastPracticed: "Not started",
          totalQuestions: 80,
          completedQuestions: 0,
          estimatedHours: 6,
          importance: "Very High",
          description: t.description || `Core syllabus concepts and drills for ${t.name}.`,
          subtopics: getSubtopicsForTopic(examId, subjectId, t.id),
          questionTypes: t.questionTypes || [],
          examLevelWeightage: t.weightage || "Core Section",
        }));
      }
    } catch {
      // Fallback to master topics
    }
  }

  const masterTopics = MASTER_TOPICS_BY_SUBJECT[subjectId] || GENERIC_DEFAULT_TOPICS;

  return masterTopics.map((item) => ({
    id: item.id,
    subjectId: subjectId,
    examId: examId || "sbi-po",
    name: item.name,
    difficulty: item.difficulty,
    progress: item.progress,
    lastPracticed: item.lastPracticed,
    totalQuestions: item.totalQuestions,
    completedQuestions: item.completedQuestions,
    estimatedHours: item.estimatedHours,
    importance: item.importance,
    description: item.description,
  }));
}

export function getTopicById(
  topicId: string,
  subjectId?: string,
  examId?: string
): Topic | undefined {
  if (examId) {
    try {
      const { getExamBlueprint } = require("./examBlueprints");
      const { getSubtopicsForTopic } = require("./subtopicRegistry");
      const bp = getExamBlueprint(examId);

      for (const s of bp?.subjects || []) {
        if (!subjectId || s.id === subjectId) {
          const match = s.topics?.find((t: { id: string }) => t.id === topicId);
          if (match) {
            return {
              id: match.id,
              subjectId: s.id,
              examId: examId,
              name: match.name,
              difficulty: (match.difficulty as any) || "Exam Level",
              progress: 0,
              lastPracticed: "Not started",
              totalQuestions: 80,
              completedQuestions: 0,
              estimatedHours: 6,
              importance: "Very High",
              description: match.description || `Target syllabus drills for ${match.name}.`,
              subtopics: getSubtopicsForTopic(examId, s.id, match.id),
              questionTypes: match.questionTypes || [],
              examLevelWeightage: match.weightage || "Core Section",
            };
          }
        }
      }
    } catch {
      // Fallback to master topics
    }
  }

  // If subjectId is known, search there first
  if (subjectId && MASTER_TOPICS_BY_SUBJECT[subjectId]) {
    const match = MASTER_TOPICS_BY_SUBJECT[subjectId].find((t) => t.id === topicId);
    if (match) {
      return {
        ...match,
        subjectId,
        examId: examId || "sbi-po",
      };
    }
  }

  // Search across all subjects
  for (const [subKey, topics] of Object.entries(MASTER_TOPICS_BY_SUBJECT)) {
    const match = topics.find((t) => t.id === topicId);
    if (match) {
      return {
        ...match,
        subjectId: subKey,
        examId: examId || "sbi-po",
      };
    }
  }

  // Check generic
  const genericMatch = GENERIC_DEFAULT_TOPICS.find((t) => t.id === topicId);
  if (genericMatch) {
    return {
      ...genericMatch,
      subjectId: subjectId || "reasoning-ability",
      examId: examId || "sbi-po",
    };
  }

  return undefined;
}

export function getAllTopics(): Topic[] {
  const all: Topic[] = [];
  for (const [subKey, topics] of Object.entries(MASTER_TOPICS_BY_SUBJECT)) {
    for (const t of topics) {
      all.push({
        ...t,
        subjectId: subKey,
        examId: "sbi-po",
      });
    }
  }
  return all;
}
