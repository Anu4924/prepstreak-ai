// Helper functions for exam lookup & filtering
export function getAllExams(): Exam[] {
  return CENTRAL_EXAM_CATALOGUE;
}

export function getExamById(id: string): Exam | undefined {
  return CENTRAL_EXAM_CATALOGUE.find((exam) => exam.id === id);
}

export function getExamsByCategory(category: string): Exam[] {
  if (!category || category === "All") return CENTRAL_EXAM_CATALOGUE;
  return CENTRAL_EXAM_CATALOGUE.filter((exam) => exam.category === category);
}

export function getAllCategories(): ExamCategory[] {
  return EXAM_CATEGORIES;
}

export function getSubCategories(category?: string): string[] {
  const exams = category && category !== "All"
    ? CENTRAL_EXAM_CATALOGUE.filter((e) => e.category === category)
    : CENTRAL_EXAM_CATALOGUE;
  const set = new Set<string>();
  exams.forEach((e) => {
    if (e.subCategory) set.add(e.subCategory);
  });
  return Array.from(set);
}

export function searchExams(
  query: string,
  category?: string,
  subCategory?: string,
  difficulty?: string
): Exam[] {
  return CENTRAL_EXAM_CATALOGUE.filter((exam) => {
    const matchesCategory =
      !category || category === "All" || exam.category === category;
    const matchesSubCategory =
      !subCategory || subCategory === "All" || exam.subCategory === subCategory;
    const matchesDifficulty =
      !difficulty || difficulty === "All" || exam.difficulty === difficulty;

    if (!matchesCategory || !matchesSubCategory || !matchesDifficulty) {
      return false;
    }

    if (!query.trim()) return true;

    const q = query.toLowerCase().trim();
    return (
      exam.name.toLowerCase().includes(q) ||
      exam.shortName.toLowerCase().includes(q) ||
      exam.officialName.toLowerCase().includes(q) ||
      exam.organization.toLowerCase().includes(q) ||
      exam.category.toLowerCase().includes(q) ||
      exam.subCategory.toLowerCase().includes(q) ||
      exam.description.toLowerCase().includes(q) ||
      exam.highlights.some((h) => h.toLowerCase().includes(q))
    );
  });
}
